CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    slot_date DATE NOT NULL,
    start_time TIME NOT NULL,
    patient_name VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL,
    active_slot_key VARCHAR(64),
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT fk_booking_doctor FOREIGN KEY (doctor_id) REFERENCES doctor (id),
    CONSTRAINT uk_booking_active_slot_key UNIQUE (active_slot_key),
    CONSTRAINT ck_booking_status CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX ix_booking_doctor_date ON booking (doctor_id, slot_date);
CREATE INDEX ix_booking_status_expires_at ON booking (status, expires_at);
