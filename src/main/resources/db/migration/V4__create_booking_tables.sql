CREATE TABLE bookings (
    id              BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id       BIGINT                   NOT NULL,
    start_time      TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time        TIMESTAMP WITH TIME ZONE NOT NULL,
    patient_id      VARCHAR(64)              NOT NULL,
    status          VARCHAR(16)              NOT NULL,
    hold_expires_at TIMESTAMP WITH TIME ZONE,
    version         BIGINT                   NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_bookings_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id),
    CONSTRAINT ck_bookings_status CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_bookings_time_range CHECK (end_time > start_time)
);

CREATE INDEX idx_bookings_doctor_start ON bookings (doctor_id, start_time);
CREATE INDEX idx_bookings_status_hold_expires ON bookings (status, hold_expires_at);

CREATE TABLE booking_slots (
    doctor_id       BIGINT                   NOT NULL,
    start_time      TIMESTAMP WITH TIME ZONE NOT NULL,
    booking_id      BIGINT,
    hold_expires_at TIMESTAMP WITH TIME ZONE,
    version         BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT pk_booking_slots PRIMARY KEY (doctor_id, start_time),
    CONSTRAINT fk_booking_slots_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id),
    CONSTRAINT fk_booking_slots_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT uk_booking_slots_booking UNIQUE (booking_id),
    CONSTRAINT ck_booking_slots_hold_has_owner CHECK (hold_expires_at IS NULL OR booking_id IS NOT NULL)
);

CREATE INDEX idx_booking_slots_hold_expires ON booking_slots (hold_expires_at);
